'use strict';
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const fs = require('node:fs/promises');
const path = require('node:path');
const { createTestServer } = require('./local-test-server.cjs');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const f = await createTestServer({ builtFrontend: process.env.RECRUITMENT_BUILT_FRONTEND === 'true' });
  let browser;
  try {
    const { ids, adminPool: db } = f;
    const project = randomUUID(), scope = randomUUID();
    await db.query('INSERT INTO projects(id,name,legal_entity_id,region_id) VALUES($1,$2,$3,$4)', [project, 'Второй проект компании', ids.legal, ids.region]);
    await db.query('INSERT INTO responsibility_scopes(id,project_id,name) VALUES($1,$2,$3)', [scope, project, 'Доставка']);
    await db.query('UPDATE access_grants SET personal_data_visible=true WHERE user_id=ANY($1::uuid[])', [[ids.admin, ids.dispatcher]]);
    await db.query('UPDATE access_grants SET project_id=$2,responsibility_scope_id=$3 WHERE user_id=$1', [ids.dispatcher, project, scope]);
    const admin = await f.devLogin(ids.admin);
    const save = async (type, body) => { const result = await f.request('PUT', `/recruitment/${type}`, { id: randomUUID(), version: 0, ...body }, admin.accessToken); assert.equal(result.status, 200, JSON.stringify(result.body)); return result.body; };
    const demand = await save('requests', { responsibilityScopeId: scope, title: 'Потребность второго проекта', city: 'Москва', kind: 'driver', quantity: 2, priority: 'normal', status: 'open', recruiterId: ids.dispatcher });
    const first = await save('candidates', { responsibilityScopeId: ids.scope, fullName: 'Общий кандидат из первого проекта', phone: '+79990971001', city: 'Москва', kind: 'driver', source: 'manual', recruiterId: ids.admin });
    const second = await save('candidates', { responsibilityScopeId: scope, fullName: 'Кандидат коллеги из второго проекта', phone: '+79990971002', city: 'Москва', kind: 'driver', source: 'manual', recruiterId: ids.dispatcher });
    const application = await save('applications', { responsibilityScopeId: scope, candidateId: first.id, requestId: demand.id, stage: 'new', recruiterId: ids.dispatcher });
    const crossTask = await save('tasks', { responsibilityScopeId: scope, candidateId: first.id, applicationId: null, title: 'Задача другого проекта', dueAt: new Date(Date.now() + 3600000).toISOString(), assigneeId: ids.admin, status: 'open' });
    browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, timezoneId: 'Europe/Moscow' });
    await context.addInitScript(session => sessionStorage.setItem('ecl.session.v2', JSON.stringify({ session })), { ...admin, rememberedDevice: false });
    const page = await context.newPage(); page.setDefaultTimeout(15000);
    const errors = []; page.on('pageerror', error => errors.push(error.message)); page.on('dialog', dialog => dialog.accept());
    await page.goto(`${f.origin}/?section=recruitment`);
    const nav = page.getByRole('navigation', { name: 'Разделы рекрутинга' });
    await page.locator(`[data-candidate-id="${first.id}"]`).waitFor();
    await page.locator(`[data-candidate-id="${second.id}"]`).waitFor();
    assert.equal(await page.getByLabel('Проект и область ответственности', { exact: true }).count(), 0);
    assert.equal(await page.getByLabel('Рекрутер', { exact: true }).inputValue(), '');
    assert.equal(await page.getByLabel('Фильтр по проекту', { exact: true }).inputValue(), '');
    console.log('PASS company opens all candidates and recruiters without an isolated workspace selector');
    await page.getByLabel('Фильтр по проекту', { exact: true }).selectOption(scope);
    await page.locator(`[data-candidate-id="${first.id}"]`).waitFor();
    await page.getByLabel(`Статус подбора · ${demand.title}`, { exact: true }).selectOption('contact');
    await page.getByText('Статус сохранён', { exact: true }).waitFor();
    const stored = await f.request('GET', `/recruitment/candidate?candidateId=${first.id}`, undefined, admin.accessToken);
    assert.equal(stored.body.applications.find(item => item.id === application.id).stage, 'contact');
    console.log('PASS candidate appears under destination project and stage mutation preserves its project');
    await page.getByLabel('Фильтр по проекту', { exact: true }).selectOption('');
    await nav.getByRole('button', { name: 'Потребности', exact: true }).click();
    const card = page.locator('.recruitment-request-card').filter({ has: page.getByRole('heading', { name: demand.title, exact: true }) });
    await card.waitFor();
    assert.ok((await card.textContent()).includes('Второй проект компании'));
    await card.getByRole('button', { name: 'Подобрать кандидата', exact: true }).click();
    const form = page.getByRole('dialog', { name: 'Подбор кандидата', exact: true });
    await form.waitFor();
    await form.getByLabel('Кандидат', { exact: true }).selectOption(second.id);
    await form.getByRole('button', { name: 'Сохранить', exact: true }).click();
    await form.waitFor({ state: 'hidden' });
    let snapshot = await f.request('GET', '/recruitment', undefined, admin.accessToken);
    assert.ok(snapshot.body.applications.some(item => item.candidateId === second.id && item.requestId === demand.id));
    await card.getByRole('button', { name: 'Изменить потребность', exact: true }).click();
    const demandForm = page.getByRole('dialog', { name: 'Потребность в подборе', exact: true });
    assert.equal(await demandForm.getByLabel('Проект', { exact: true }).inputValue(), scope);
    await demandForm.getByLabel('Название потребности', { exact: true }).fill('Обновлённая потребность другого проекта');
    await demandForm.getByRole('button', { name: 'Сохранить', exact: true }).click();
    await demandForm.waitFor({ state: 'hidden' });
    snapshot = await f.request('GET', '/recruitment', undefined, admin.accessToken);
    assert.equal(snapshot.body.requests.find(item => item.id === demand.id).title, 'Обновлённая потребность другого проекта');
    console.log('PASS cards expose projects; create and edit operations use the record project');
    await nav.getByRole('button', { name: 'Кандидаты', exact: true }).click();
    await page.locator(`[data-candidate-id="${first.id}"]`).getByRole('button', { name: first.fullName, exact: true }).click();
    const detail = page.getByRole('dialog', { name: `Карточка ${first.fullName}`, exact: true });
    await detail.waitFor();
    await detail.getByRole('button', { name: 'Записать контакт', exact: true }).click();
    const contact = page.getByRole('dialog', { name: 'Результат контакта', exact: true });
    await contact.getByLabel('Подбор по обращению', { exact: true }).selectOption(application.id);
    await contact.getByLabel('Комментарий к контакту', { exact: true }).fill('Контакт по потребности другого проекта');
    await contact.getByRole('button', { name: 'Сохранить', exact: true }).click();
    await contact.waitFor({ state: 'hidden' });
    const after = await f.request('GET', `/recruitment/candidate?candidateId=${first.id}`, undefined, admin.accessToken);
    assert.ok(after.body.contacts.some(item => item.applicationId === application.id && item.responsibilityScopeId === scope));
    await page.getByRole('button', { name: 'Закрыть карточку', exact: true }).click();
    await nav.getByRole('button', { name: 'Задачи', exact: true }).click();
    const taskCard = page.locator('.recruitment-task-card').filter({ has: page.getByRole('heading', { name: crossTask.title, exact: true }) });
    await taskCard.getByRole('button', { name: 'Изменить задачу', exact: true }).click();
    const taskForm = page.getByRole('dialog', { name: 'Задача рекрутеру', exact: true });
    await taskForm.getByLabel('Название задачи', { exact: true }).fill('Задача другого проекта обновлена');
    await taskForm.getByRole('button', { name: 'Сохранить', exact: true }).click();
    await taskForm.waitFor({ state: 'hidden' });
    const savedTask = (await f.request('GET', '/recruitment', undefined, admin.accessToken)).body.tasks.find(item => item.id === crossTask.id);
    assert.equal(savedTask.responsibilityScopeId, scope);
    assert.equal(savedTask.title, 'Задача другого проекта обновлена');
    await nav.getByRole('button', { name: 'Кандидаты', exact: true }).click();
    await page.locator(`[data-candidate-id="${first.id}"]`).waitFor();
    const out = path.resolve(__dirname, '../.local/recruitment-company-browser-qa'); await fs.mkdir(out, { recursive: true });
    await page.screenshot({ path: path.join(out, 'company-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(out, 'company-mobile.png'), fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    assert.deepEqual(errors, []);
    console.log('PASS cross-project contact, next action, desktop and mobile');
  } finally { if (browser) await browser.close(); await f.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
