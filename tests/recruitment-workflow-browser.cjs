    assert.equal(await page.locator(`[data-candidate-id="${otherRecruiterPerson.id}"]`).count(), 0);
    const queues = page.getByLabel('Очереди работы', { exact: true });
    await queues.getByRole('button', { name: /^Без следующего шага/ }).click();
    await page.locator(`.recruitment-board [data-candidate-id="${withoutApplication.id}"]`).waitFor({ state: 'hidden' });
    await listButton.click();
    assert.equal(await queues.getByRole('button', { name: /^Без следующего шага/ }).getAttribute('aria-pressed'), 'true');
    assert.deepEqual(await displayedCandidateIds(), [overviewPerson.id], 'The next-action queue survives switching to the list');
    await queues.getByRole('button', { name: /^Просрочено/ }).click();
    await page.locator(`.recruitment-worklist [data-candidate-id="${withoutApplication.id}"]`).waitFor();
