'use strict';
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { createTestServer } = require('./local-test-server.cjs');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const fixture = await createTestServer();
  let browser;
  try {
    const { ids, adminPool: db } = fixture;
    const legal = randomUUID(), project = randomUUID(), scope = randomUUID();
    await db.query('UPDATE legal_entities SET name=$2 WHERE id=$1', [ids.legal, 'А Учебная компания']);
    await db.query('INSERT INTO legal_entities(id,name) VALUES($1,$2)', [legal, 'Я Рабочая компания']);
    await db.query('INSERT INTO projects(id,name,legal_entity_id,region_id) VALUES($1,$2,$3,$4)', [project, 'Рабочий рекрутинг', legal, ids.region]);
    await db.query('INSERT INTO responsibility_scopes(id,project_id,name) VALUES($1,$2,$3)', [scope, project, 'Подбор']);
    await db.query('UPDATE access_grants SET personal_data_visible=true WHERE user_id=$1', [ids.admin]);
    await db.query('INSERT INTO access_grants(user_id,legal_entity_id,region_id,project_id,responsibility_scope_id,personal_data_visible) VALUES($1,$2,$3,$4,$5,true)', [ids.admin, legal, ids.region, project, scope]);
    const session = await fixture.devLogin(ids.admin);
    const api = async (method, path, body) => {
      const result = await fixture.request(method, path, body, session.accessToken);
      assert.ok([200, 201].includes(result.status), `${result.status}: ${JSON.stringify(result.body)}`);
      return result.body;
    };
    const candidateInput = (responsibilityScopeId, name, phone) => ({ id: randomUUID(), responsibilityScopeId, version: 0, fullName: name, phone, city: 'Москва', kind: 'driver', recruiterId: ids.admin, source: 'manual' });
    await api('PUT', '/recruitment/candidates', candidateInput(scope, 'Рабочий кандидат', '+79990003501'));
    await api('PUT', '/recruitment/requests', { id: randomUUID(), responsibilityScopeId: scope, version: 0, title: 'Рабочая потребность', city: 'Москва', kind: 'driver', quantity: 1, priority: 'normal', status: 'open', recruiterId: ids.admin });
    const catalog = await api('GET', '/recruitment/context');
    assert.equal(catalog.scopes[0].responsibilityScopeId, ids.scope);
    assert.equal(catalog.defaultResponsibilityScopeId, scope);
    browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
    const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
    await context.addInitScript(value => sessionStorage.setItem('ecl.session.v2', JSON.stringify({ session: value })), { ...session, rememberedDevice: false });
    const page = await context.newPage(); page.setDefaultTimeout(15000);
    const errors = []; page.on('pageerror', error => errors.push(error.message)); page.on('dialog', dialog => dialog.accept());
    const pendingSave = suffix => page.waitForResponse(response => response.url().endsWith(suffix) && response.request().method() === 'PUT');
    const assertSavedScope = async (pending, expected) => { const response = await pending; assert.equal(response.status(), 200, await response.text()); const saved = await response.json(); assert.equal(saved.responsibilityScopeId, expected); return saved; };
    await page.goto(`${fixture.origin}/?section=recruitment&recruitmentScope=${ids.scope}`);
    await page.getByRole('button', { name: 'Добавить кандидата', exact: true }).first().click();
    let dialog = page.getByRole('dialog', { name: 'Кандидат', exact: true });
    await dialog.getByLabel('ФИО', { exact: true }).fill('Новый рабочий кандидат');
    await dialog.getByLabel('Телефон', { exact: true }).fill('+79990003502');
    await dialog.getByLabel('Город', { exact: true }).fill('Москва');
    let pending = pendingSave('/recruitment/candidates');
    await dialog.getByRole('button', { name: 'Сохранить', exact: true }).click();
    const candidate = await assertSavedScope(pending, scope);
    assert.equal(candidate.legalEntityId, legal);
    await page.getByRole('button', { name: 'Закрыть карточку', exact: true }).click();
    const nav = page.getByRole('navigation', { name: 'Разделы рекрутинга' });
    await nav.getByRole('button', { name: 'Потребности', exact: true }).click();
    await page.getByRole('button', { name: 'Создать потребность', exact: true }).first().click();
    dialog = page.getByRole('dialog', { name: 'Потребность в подборе', exact: true });
    await dialog.getByLabel('Название потребности', { exact: true }).fill('Новая рабочая потребность');
    await dialog.getByLabel('Город', { exact: true }).fill('Москва');
    pending = pendingSave('/recruitment/requests');
    await dialog.getByRole('button', { name: 'Сохранить', exact: true }).click();
    await assertSavedScope(pending, scope);
    await dialog.waitFor({ state: 'hidden' });
    await page.getByRole('navigation', { name: 'Разделы', exact: true }).getByRole('button', { name: 'Оформление', exact: true }).click();
    const onboarding = page.getByRole('navigation', { name: 'Разделы оформления' });
    const createTemplate = async (name, expectedScope) => {
      await onboarding.getByRole('button', { name: 'Конструктор анкет', exact: true }).click();
      await page.getByRole('button', { name: 'Создать форму', exact: true }).click();
      await page.getByLabel('Название формы', { exact: true }).fill(name);
      await page.getByLabel('Направление оформления', { exact: true }).fill('Оформление водителей');
      await page.getByLabel('Информация об обработке данных', { exact: true }).fill('Синтетическая форма проверки.');
      const response = pendingSave('/onboarding/templates');
      await page.getByRole('button', { name: 'Опубликовать форму', exact: true }).click();
      const result = await assertSavedScope(response, expectedScope);
      await page.getByRole('button', { name: 'Создать форму', exact: true }).waitFor();
      return result;
    };
    const workingTemplate = await createTemplate('Форма рабочей компании', scope);
    const otherCandidate = await api('PUT', '/recruitment/candidates', candidateInput(ids.scope, 'Кандидат другой компании', '+79990003503'));
    await page.goto(`${fixture.origin}/?section=recruitment`);
    await page.locator(`[data-candidate-id="${otherCandidate.id}"]`).getByRole('button', { name: otherCandidate.fullName, exact: true }).click();
    await page.getByRole('button', { name: 'Оформить кандидата', exact: true }).click();
    await page.getByText('Для выбранного кандидата пока нет опубликованной формы. Создайте и опубликуйте форму в конструкторе.', { exact: true }).waitFor();
    assert.equal(await page.getByLabel('Форма оформления', { exact: true }).count(), 0);
    const otherTemplate = await createTemplate('Форма компании кандидата', ids.scope);
    await onboarding.getByRole('button', { name: 'Анкеты', exact: true }).click();
    const templates = page.getByLabel('Форма оформления', { exact: true });
    assert.equal(await templates.locator(`option[value="${workingTemplate.id}"]`).count(), 0);
    await templates.selectOption(otherTemplate.id);
    const created = page.waitForResponse(response => response.url().endsWith('/onboarding/sessions') && response.request().method() === 'POST');
    await page.getByRole('button', { name: 'Начать оформление', exact: true }).click();
    const sessionResponse = await created;
    assert.equal(sessionResponse.status(), 200);
    const onboardingSession = await sessionResponse.json();
    const stored = (await db.query('SELECT legal_entity_id,responsibility_scope_id,candidate_id FROM recruitment_onboarding_sessions WHERE id=$1', [onboardingSession.id])).rows[0];
    assert.equal(stored.legal_entity_id, ids.legal);
    assert.equal(stored.responsibility_scope_id, ids.scope);
    assert.equal(stored.candidate_id, otherCandidate.id);
    assert.deepEqual(errors, []);
    console.log('PASS populated company supplies new candidates, demands and templates; selected candidate limits onboarding to its own company');
  } finally { if (browser) await browser.close(); await fixture.close(); }
})().catch(error => { console.error(error.stack); process.exit(1); });
