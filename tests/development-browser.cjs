    assert.ok(overlay.y >= -1 && overlay.y <= 1 && overlay.height <= 845, 'Dialog overlay covers the viewport');
    await adminPage.screenshot({ path: path.join(out, 'ticket-mobile.png') });
    assert.ok(await adminPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile dialog must fit viewport');
    console.log('PASS responsive desktop board and mobile ticket');
    const mobileDialog = adminPage.getByRole('dialog');
    await mobileDialog.getByLabel('Описание',{exact:true}).fill('Мой черновик до комментария');
    const beforeComment = (await request('GET', `/development/tickets/${ticket.id}?responsibilityScopeId=${ids.scope}`,undefined,admin.accessToken)).body.ticket;
    assert.equal((await request('PUT','/development/tickets',{id:beforeComment.id,responsibilityScopeId:ids.scope,title:beforeComment.title,description:'Параллельная правка коллеги',section:beforeComment.section,status:beforeComment.status,version:beforeComment.version},admin.accessToken)).status,200);
    await mobileDialog.getByLabel('Комментарий',{exact:true}).fill('Уточнение с открытым черновиком');
    response=adminPage.waitForResponse(r=>r.url().endsWith('/development/comments')&&r.request().method()==='POST');
    await mobileDialog.getByRole('button',{name:'Добавить комментарий',exact:true}).click();
    assert.equal((await response).status(),201);
