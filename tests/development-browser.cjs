    await merge.click();
    const transferred = await response;
    assert.equal(transferred.status(),200);
    const transfer = await transferred.json();
    assert.equal(transfer.status,'in_progress','Quick transfer intent survives conflict');
    assert.ok(transfer.description.endsWith('Уточнение коллеги.'),'Untouched latest fields survive conflict merge');
    console.log('PASS stale board read ignored and quick production transfer survives a conflict');
    await move('review');
    await move('done');
    const saved = await request('GET', `/development/tickets/${ticket.id}?responsibilityScopeId=${ids.scope}`, undefined, admin.accessToken);
    assert.equal(saved.status, 200);
    assert.equal(saved.body.ticket.status, 'done');
    assert.equal(saved.body.ticket.number, ticket.number);
    assert.ok(saved.body.events.some(event => event.text === 'Повторяется после повторного входа.'));
    assert.equal(saved.body.events.filter(event => event.type === 'status').length, 5);
    console.log('PASS administrator completes both funnels with one ticket and preserved history');

    // Concurrent change: the browser keeps the user's text on HTTP 409.
    await detail.getByLabel('Описание', { exact: true }).fill('Черновик автора проверки — не терять');
    const current = saved.body.ticket;
    const update = await request('PUT', '/development/tickets', { id: current.id, responsibilityScopeId: ids.scope, title: current.title, description: current.description, section: current.section, status: 'review', version: current.version }, admin.accessToken);
    assert.equal(update.status, 200);
    response = adminPage.waitForResponse(r => r.url().endsWith('/development/tickets') && r.request().method() === 'PUT');
    await detail.getByRole('button', { name: /Сохранить/ }).click();
    assert.equal((await response).status(), 409);
    assert.equal(await detail.getByLabel('Описание', { exact: true }).inputValue(), 'Черновик автора проверки — не терять');
    console.log('PASS concurrent update does not overwrite the server or discard the draft');
    adminPage.on('dialog', d => d.accept());
    await adminPage.reload();
    await adminPage.getByRole('button', { name: /Продакшен/ }).click();
    await adminPage.getByText(title, { exact: true }).waitFor();
    const out = path.resolve(__dirname, '../.local/development-browser-qa' + (process.env.DEVELOPMENT_BUILT_FRONTEND === 'true' ? '-built' : ''));
    await fs.mkdir(out, { recursive: true });
    await adminPage.screenshot({ path: path.join(out, 'production-desktop.png'), fullPage: true });
    await adminPage.setViewportSize({ width: 390, height: 844 });
