    await adminPage.waitForResponse(r => r.url().includes('/api/v1/development?') && r.request().method() === 'GET');
    await adminPage.locator('.development-column.stage-clarifying').getByText(title, { exact: true }).waitFor();
    await move('ready');
    const beforeTransfer = await request('GET', `/development/tickets/${ticket.id}?responsibilityScopeId=${ids.scope}`, undefined, admin.accessToken);
    const b = beforeTransfer.body.ticket;
    const parallel = await request('PUT', '/development/tickets', { id:b.id,responsibilityScopeId:ids.scope,title:b.title,description:b.description+' Уточнение коллеги.',section:b.section,status:b.status,version:b.version }, admin.accessToken);
    assert.equal(parallel.status, 200);
    response = adminPage.waitForResponse(r => r.url().endsWith('/development/tickets') && r.request().method() === 'PUT');
