'use strict';
// Real API and disposable synthetic PostgreSQL fixture; no production credentials.
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs/promises');
const { createTestServer } = require('./local-test-server.cjs');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  const f = await createTestServer({ builtFrontend: process.env.PLANNING_BUILT_FRONTEND === 'true' });
  let browser;
  try {
    await f.adminPool.query('UPDATE access_grants SET personal_data_visible=true WHERE user_id=ANY($1::uuid[])', [[f.ids.admin, f.ids.dispatcher]]);
    await f.adminPool.query("UPDATE users SET role='manager',display_name='Менеджер конструктора' WHERE id=$1", [f.ids.dispatcher]);
    await f.adminPool.query("UPDATE projects SET name='APPIA Данон' WHERE id=$1", [f.ids.project]);
    const admin = await f.devLogin(f.ids.admin);
    const phone = '+79990000888';
    const issued = await f.request('POST', `/access/users/${f.ids.dispatcher}/password`, { phone }, admin.accessToken);
    assert.equal(issued.status, 201);
    const login = await f.request('POST', '/auth/password', { phone, password: issued.body.password });
    assert.equal(login.status, 200);
    const token = login.body.accessToken;
    const options = await f.request('GET', `/planning/options?responsibilityScopeId=${f.ids.scope}`, undefined, token);
    assert.equal(options.status, 200);
    const readPlan = async date => {
      const result = await f.request('GET', `/planning?date=${date}&responsibilityScopeId=${f.ids.scope}`, undefined, token);
      assert.equal(result.status, 200); return result.body;
    };
    browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
    const browserContext = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] });
    const page = await browserContext.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('dialog', dialog => dialog.accept());
    const savePlan = async () => {
      const responseReady = page.waitForResponse(response => response.request().method() === 'PUT' && response.url().endsWith('/api/v1/planning'));
      await page.getByRole('button', { name: 'Сохранить план', exact: true }).click();
      const response = await responseReady;
      assert.equal(response.status(), 200, JSON.stringify(await response.json()));
      await page.getByText('План сохранён', { exact: true }).waitFor();
      return response.json();
    };
    const saveForm = async version => {
      const responseReady = page.waitForResponse(response => response.request().method() === 'PUT' && response.url().endsWith('/api/v1/planning/templates'));
      await page.getByRole('button', { name: 'Сохранить форму', exact: true }).click();
      const response = await responseReady;
      const data = await response.json();
      assert.equal(response.status(), 200, JSON.stringify(data));
      await page.getByText(`Форма сохранена. Версия ${version}.`, { exact: true }).waitFor();
      return data.template;
    };
    const populateAssignment = async () => {
      await page.getByRole('button', { name: 'Добавить первое назначение', exact: true }).click();
      const assignment = page.locator('.planning-assignment').first();
      await assignment.getByLabel('Водитель', { exact: true }).selectOption(f.ids.drivers[0]);
      await assignment.getByLabel('Машина', { exact: true }).selectOption(options.body.vehicles[0].id);
      await assignment.getByLabel('Время выхода, назначение 1', { exact: true }).fill('05:15');
      return assignment;
    };
    await page.goto(f.origin);
    await page.locator('#login-phone').fill(phone);
    await page.locator('#login-password').fill(issued.body.password);
    await page.getByRole('button', { name: 'Войти', exact: true }).click();
    await page.getByRole('button', { name: 'Добавить первое назначение', exact: true }).waitFor();
    const initialDate = await page.getByLabel('Дата рейсов', { exact: true }).inputValue();
    assert.equal(await page.getByLabel('Форма подачи клиенту', { exact: true }).inputValue(), 'appia@1');
    await populateAssignment();
    const originalPlan = await savePlan();
    assert.equal(originalPlan.templateSnapshot.id, 'appia');

    await page.getByRole('button', { name: 'Конструктор форм', exact: true }).click();
    await page.getByRole('heading', { name: 'Конструктор форм', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Новая форма', exact: true }).click();
    await page.getByLabel('Название формы', { exact: true }).fill('Новый клиент · тест');
    await page.getByLabel('Название поля 1 в разделе Основная форма', { exact: true }).fill('Маршрут клиента');
    await page.getByLabel('Обязательное поле Маршрут клиента', { exact: true }).check();
    await page.getByRole('button', { name: 'Добавить поле в раздел Основная форма', exact: true }).click();
    await page.getByLabel('Название поля 2 в разделе Основная форма', { exact: true }).fill('ФИО для заявки');
    await page.getByLabel('Источник поля 2 в разделе Основная форма', { exact: true }).selectOption('driver_name');
    const formV1 = await saveForm(1);
    const routeKey = formV1.sections[0].columns[0].key;
    const driverKey = formV1.sections[0].columns[1].key;
    assert.equal(formV1.sections[0].columns[0].required, true);
    assert.equal(formV1.sections[0].columns[1].source, 'driver_name');
    const catalog = await f.request('GET', `/planning/templates?responsibilityScopeId=${f.ids.scope}`, undefined, token);
    assert.equal(catalog.body.defaultTemplateId, formV1.id);
    assert.deepEqual((await readPlan(initialDate)).templateSnapshot, originalPlan.templateSnapshot);
    await page.getByRole('button', { name: 'Закрыть конструктор', exact: true }).click();
    assert.equal(await page.getByLabel('Форма подачи клиенту', { exact: true }).inputValue(), 'appia@1');
    await page.getByRole('button', { name: 'Применить сохранённую форму', exact: true }).click();
    assert.equal(await page.getByLabel('Форма подачи клиенту', { exact: true }).inputValue(), `${formV1.id}@1`);
    assert.deepEqual((await readPlan(initialDate)).templateSnapshot, originalPlan.templateSnapshot, 'application changes the draft until the manager saves the plan');
    await page.getByRole('button', { name: 'Форма клиента', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: 'Скачать CSV', exact: true }).isDisabled(), true);
    await page.getByText('Назначение 1, Маршрут клиента: обязательное поле.', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Назначения', exact: true }).click();
    await page.locator('.planning-assignment').first().locator('summary').click();
    await page.getByLabel('Маршрут клиента', { exact: true }).fill('Склад А — магазин Б');
    assert.match(await page.getByLabel('ФИО для заявки', { exact: true }).inputValue(), /Водитель/);
    const customPlan = await savePlan();
    assert.equal(customPlan.templateVersion, 1);
    assert.equal(customPlan.rows[0].clientFields[routeKey], 'Склад А — магазин Б');
    assert.ok(!Object.hasOwn(customPlan.rows[0].clientFields, driverKey), 'automatic driver data must not become a stored override');
    await page.getByRole('button', { name: 'Форма клиента', exact: true }).click();
    const downloadReady = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Скачать CSV', exact: true }).click();
    const download = await downloadReady;
    const stream = await download.createReadStream();
    let csv = ''; for await (const chunk of stream) csv += chunk.toString('utf8');
    assert.ok(csv.startsWith('\uFEFF"Маршрут клиента";"ФИО для заявки"'));
    assert.ok(csv.includes('Склад А — магазин Б'));
    assert.ok(csv.includes('Водитель'));

    await page.getByRole('button', { name: 'Конструктор форм', exact: true }).click();
    await page.getByLabel('Название поля 1 в разделе Основная форма', { exact: true }).fill('Маршрут доставки');
    await page.getByRole('button', { name: 'Переместить поле 2 вверх в разделе Основная форма', exact: true }).click();
    const out = path.resolve(__dirname, '../.local/planning-constructor-qa');
    await fs.mkdir(out, { recursive: true });
    await page.screenshot({ path: path.join(out, 'desktop-builder.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'builder must fit a 390px viewport');
    await page.screenshot({ path: path.join(out, 'mobile-builder.png'), fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    const formV2 = await saveForm(2);
    assert.deepEqual(formV2.sections[0].columns.map(c => c.key), [driverKey, routeKey]);
    assert.deepEqual(formV2.sections[0].columns.map(c => c.label), ['ФИО для заявки', 'Маршрут доставки']);
    assert.deepEqual((await readPlan(initialDate)).templateSnapshot, customPlan.templateSnapshot);
    await page.getByRole('button', { name: 'Закрыть конструктор', exact: true }).click();
    assert.equal(await page.getByLabel('Форма подачи клиенту', { exact: true }).inputValue(), `${formV1.id}@1`);
    assert.deepEqual(await page.locator('.planning-client-table thead th').allTextContents(), ['Маршрут клиента', 'ФИО для заявки']);

    const next = new Date(`${initialDate}T12:00:00.000Z`); next.setUTCDate(next.getUTCDate() + 1);
    const laterDate = next.toISOString().slice(0, 10);
    await page.getByLabel('Дата рейсов', { exact: true }).fill(laterDate);
    await page.getByRole('button', { name: 'Назначения', exact: true }).click();
    await page.getByRole('button', { name: 'Добавить первое назначение', exact: true }).waitFor();
    assert.equal(await page.getByLabel('Форма подачи клиенту', { exact: true }).inputValue(), `${formV1.id}@2`);
    await populateAssignment();
    await page.locator('.planning-assignment').first().locator('summary').click();
    await page.getByLabel('Маршрут доставки', { exact: true }).fill('Склад В — магазин Г');
    const laterPlan = await savePlan();
    assert.equal(laterPlan.templateVersion, 2);
    assert.deepEqual(laterPlan.templateSnapshot, formV2);
    await page.reload();
    await page.locator('.planning-assignment').first().waitFor();
    assert.equal(await page.getByLabel('Дата рейсов', { exact: true }).inputValue(), initialDate);
    assert.equal(await page.getByLabel('Форма подачи клиенту', { exact: true }).inputValue(), `${formV1.id}@1`);
    await page.getByLabel('Дата рейсов', { exact: true }).fill(laterDate);
    await page.locator('.planning-assignment').first().waitFor();
    assert.equal(await page.getByLabel('Форма подачи клиенту', { exact: true }).inputValue(), `${formV1.id}@2`);
    await page.locator('.planning-assignment').first().locator('summary').click();
    assert.equal(await page.getByLabel('Маршрут доставки', { exact: true }).inputValue(), 'Склад В — магазин Г');
    await page.getByRole('button', { name: 'Форма клиента', exact: true }).click();
    assert.deepEqual(await page.locator('.planning-client-table thead th').allTextContents(), ['ФИО для заявки', 'Маршрут доставки']);
    await page.screenshot({ path: path.join(out, 'desktop-preview.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'client preview must fit a 390px viewport');
    await page.screenshot({ path: path.join(out, 'mobile-preview.png'), fullPage: true });
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ managerLogin: 'passed', createForm: 'passed', requiredFieldBlocksExport: 'passed', automaticDriver: 'passed', csv: 'passed', explicitApplyOnly: 'passed', oldPlanVersionRetained: 'passed', editAndReorder: 'passed', latestDefaultForNewDate: 'passed', persistedReload: 'passed', mobileOverflow: false, javascriptErrors: 0, builtFrontend: process.env.PLANNING_BUILT_FRONTEND === 'true', screenshots: out }));
  } finally { if (browser) await browser.close(); await f.close(); }
})().catch(error => { console.error(error.stack); process.exitCode = 1; });
