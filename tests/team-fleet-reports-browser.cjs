    assert.equal(targetSaved.length, 1);
    assert.equal(targetSaved[0].conversationId, targetReports.id);
    assert.equal(targetSaved[0].responsibilityScopeId, targetScope);
    assert.deepEqual(targetSaved[0].sourceScopeIds, []);
