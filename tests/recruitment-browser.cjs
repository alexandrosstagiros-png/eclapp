    await page.getByRole('button', { name: 'Выполненные', exact: true }).click();
    await page.getByRole('heading', { name: task.title, exact: true }).waitFor();
    assert.equal((await snapshot()).tasks[0].status, 'done');
    console.log('PASS request, candidate, hh handoff, interview and durable cross-section reminder completion');

    await tabs.getByRole('button', { name: 'Кандидаты', exact: true }).click();
    await page.getByRole('button', { name: 'Список', exact: true }).click();
    await page.getByRole('button', { name: 'Добавить кандидата', exact: true }).first().click();
    await form().getByLabel('ФИО', { exact: true }).fill('Тестовый Перевозчик');
