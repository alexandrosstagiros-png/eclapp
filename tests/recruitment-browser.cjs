    await form().getByLabel('Тип кузова / автомобиль', { exact: true }).fill('Фургон');
    await form().getByLabel('Габариты кузова', { exact: true }).fill('4 × 2 × 2 м');
    await form().getByLabel('Грузоподъёмность / объём', { exact: true }).fill('1,5 т / 12 м³');
    const carrier = await save('candidates');
    await form().getByText('4 × 2 × 2 м · 1,5 т / 12 м³', { exact: true }).waitFor();
    await form().getByRole('button', { name: 'Закрыть карточку', exact: true }).click();
    await page.getByLabel('Город кандидата', { exact: true }).selectOption('Тула');
    await page.waitForFunction(() => !document.querySelector('.recruitment-loading') && document.querySelectorAll('.recruitment-worklist tbody tr').length === 1);
    assert.equal(await page.locator('.recruitment-worklist tbody tr').count(), 1);
    await page.getByRole('button', { name: carrier.fullName, exact: true }).waitFor();
    await page.getByLabel('Город кандидата', { exact: true }).selectOption('');
    await page.getByLabel('Направление', { exact: true }).selectOption('driver');
    await page.waitForFunction(() => !document.querySelector('.recruitment-loading') && document.querySelectorAll('.recruitment-worklist tbody tr').length === 1);
    assert.equal(await page.locator('.recruitment-worklist tbody tr').count(), 1);
    await page.getByLabel('Направление', { exact: true }).selectOption('');

    await page.getByRole('button', { name: candidate.fullName, exact: true }).click();
    await form().getByRole('button', { name: 'Изменить этап', exact: true }).click();
