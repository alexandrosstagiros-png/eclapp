    assert.equal(await hh.getAttribute('target'), '_blank');
    assert.match(await hh.getAttribute('rel'), /noopener/);

    await form().getByRole('button', { name: 'Добавить в подбор', exact: true }).click();
    await form().getByLabel('Потребность', { exact: true }).selectOption(demand.id);
    await form().getByLabel('Этап подбора', { exact: true }).selectOption('interview');
    let application = await save('applications');
    await form().getByRole('button', { name: 'Напомнить о кандидате', exact: true }).click();
    await form().getByLabel('Название задачи', { exact: true }).fill('Узнать решение по утреннему маршруту');
    await form().getByLabel('Дата и время напоминания', { exact: true }).fill(await localMinute(-120000));
    const task = await save('tasks');
    await page.getByText('Напоминания по подбору: 1', { exact: true }).waitFor();
    await form().getByRole('button', { name: 'Закрыть карточку', exact: true }).click();
    await page.getByRole('button', { name: 'Планирование', exact: true }).click();
    await page.getByRole('heading', { name: 'Планирование', exact: true }).waitFor();
