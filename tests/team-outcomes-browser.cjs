'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const { createTestServer } = require('./local-test-server.cjs');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const f = await createTestServer({ staffTeamActors: true, builtFrontend: process.env.TEAM_BUILT_FRONTEND === 'true' });
  let browser;
  try {
    const { ids, request, devLogin } = f;
    await f.adminPool.query('UPDATE access_grants SET personal_data_visible=true');
    await f.adminPool.query(`UPDATE users SET display_name=CASE id WHEN $1 THEN 'Руководитель итогов' WHEN $2 THEN 'Коллега с короной' WHEN $3 THEN 'Руководитель без отчёта' ELSE display_name END WHERE id=ANY($4::uuid[])`, [ids.drivers[0], ids.drivers[1], ids.mechanic, [ids.drivers[0], ids.drivers[1], ids.mechanic]]);
    const admin = await devLogin(ids.admin), manager = await devLogin(ids.drivers[0]), peer = await devLogin(ids.drivers[1]);
    const api = async (method, route, body, session = admin) => {
      const result = await request(method, route, body, session.accessToken);
      assert.ok([200, 201].includes(result.status), `${method} ${route}: ${result.status} ${JSON.stringify(result.body)}`); return result.body;
    };
    const scoped = route => `${route}?responsibilityScopeId=${ids.scope}`;
    for (const [userId, managerId] of [[ids.drivers[1], ids.drivers[0]], [ids.dispatcher, ids.mechanic]]) await api('PUT', `/team/organization/employees/${userId}`, { responsibilityScopeId: ids.scope, operationId: randomUUID(), version: 0, managerId, positionId: null });
    const channel = await api('POST', '/team/conversations', { id: randomUUID(), responsibilityScopeId: ids.scope, kind: 'channel', title: 'Работа и благодарности', memberIds: [] });
    const peerMessage = await api('POST', '/team/messages', { id: randomUUID(), responsibilityScopeId: ids.scope, conversationId: channel.id, parentId: null, text: 'Сообщение коллеги для проверки короны' }, peer);
    browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
    const errors = [], output = path.resolve(__dirname, '../.local/team-outcomes-qa');
    await fs.mkdir(output, { recursive: true });
    async function pageFor(session) {
      const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, timezoneId: 'Europe/Moscow' });
      await context.addInitScript(value => sessionStorage.setItem('ecl.session.v2', JSON.stringify({ session: value })), { ...session, rememberedDevice: false });
      const page = await context.newPage(); page.setDefaultTimeout(20000); page.on('pageerror', error => errors.push(error.message));
      page.on('dialog', dialog => dialog.accept());
      await page.goto(`${f.origin}/?section=team`); await page.getByRole('heading', { name: 'Команда', exact: true }).waitFor(); return page;
    }
    const tabs = page => page.getByRole('navigation', { name: 'Разделы команды' });
    const m = await pageFor(manager);
    await m.getByText(channel.title, { exact: true }).first().click();
    await m.locator(`[data-message-id="${peerMessage.id}"]`).waitFor();
    assert.equal(await m.locator(`[data-message-id="${peerMessage.id}"] .team-crown`).count(), 0);
    await tabs(m).getByRole('button', { name: 'Итоги', exact: true }).click();
    await m.getByLabel('Что сделано', { exact: true }).fill('Синтетический приватный черновик недели');
    await m.getByLabel('Что в работе', { exact: true }).fill('Согласование документа');
    await m.getByLabel('Какие есть препятствия', { exact: true }).fill('нет');
    await m.getByRole('checkbox', { name: 'Коллега с короной', exact: true }).check();
    await m.getByLabel('Причина благодарности Коллега с короной', { exact: true }).fill('За проверку документов');
    await m.getByRole('button', { name: 'Сохранить черновик', exact: true }).click();
    await m.getByText('Черновик сохранён. Он виден только вам.', { exact: true }).waitFor();
    assert.deepEqual((await api('GET', scoped('/team/recognition'), undefined, peer)).recognition, []);
    const a = await pageFor(admin);
    await tabs(a).getByRole('button', { name: 'Итоги', exact: true }).click();
    await a.getByRole('button', { name: 'Руководитель итогов', exact: true }).click();
    await a.getByText('Отчёт пока не сдан. Черновик доступен только автору.', { exact: true }).waitFor();
    assert.equal(await a.getByText('Синтетический приватный черновик недели', { exact: true }).count(), 0);
    await a.getByRole('button', { name: 'Руководитель без отчёта', exact: true }).click();
    await a.getByText('Отчёт пока не сдан. Черновик доступен только автору.', { exact: true }).waitFor();
    assert.equal(await a.getByRole('button', { name: 'Сдать итоги', exact: true }).count(), 0);
    await a.screenshot({ path: path.join(output, 'admin-compliance-desktop.png'), fullPage: true });
    await m.bringToFront(); await m.reload(); await tabs(m).getByRole('button', { name: 'Итоги', exact: true }).click();
    await m.getByLabel('Что сделано', { exact: true }).waitFor();
    assert.equal(await m.getByLabel('Что сделано', { exact: true }).inputValue(), 'Синтетический приватный черновик недели');
    await m.getByRole('button', { name: 'Сдать итоги', exact: true }).click();
    await m.getByText('Итоги сданы. Благодарности начислены.', { exact: true }).waitFor();
    assert.deepEqual((await api('GET', scoped('/team/recognition'), undefined, peer)).recognition, [{ userId: ids.drivers[1], count: 1 }]);
    await tabs(m).getByRole('button', { name: 'Обсуждения', exact: true }).click();
    await m.getByText(channel.title, { exact: true }).first().click();
    await m.locator(`[data-message-id="${peerMessage.id}"]`).getByLabel('Благодарностей: 1', { exact: true }).waitFor();
    await m.screenshot({ path: path.join(output, 'crown-in-chat.png'), fullPage: true });
    await tabs(m).getByRole('button', { name: 'Итоги', exact: true }).click();
    await m.getByRole('tab', { name: 'Месячные итоги', exact: true }).click();
    await m.getByLabel('Что сделано', { exact: true }).fill('Закрыт план месяца');
    await m.getByLabel('Что в работе', { exact: true }).fill('Следующий проект');
    await m.getByLabel('Какие есть препятствия', { exact: true }).fill('нет');
    await m.getByRole('button', { name: 'Сдать итоги', exact: true }).click();
    await m.getByRole('alert').filter({ hasText: 'Заполните обязательные поля' }).waitFor();
    await m.getByLabel('Фокус следующего месяца', { exact: true }).fill('Сократить срок согласования');
    await m.getByRole('button', { name: 'Сдать итоги', exact: true }).click();
    await m.getByText('Итоги сданы.', { exact: true }).waitFor();
    await m.getByText('Сократить срок согласования', { exact: true }).waitFor();
    assert.equal(await m.getByLabel('Фокус следующего месяца', { exact: true }).count(), 0);
    await m.screenshot({ path: path.join(output, 'monthly-desktop.png'), fullPage: true });
    await m.setViewportSize({ width: 390, height: 844 });
    assert.ok(await m.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Outcomes mobile layout must not overflow');
    await m.screenshot({ path: path.join(output, 'monthly-mobile.png'), fullPage: true });

    // A task's durable assignment message is also a mention; the card opens the same task.
    const task = await api('POST', '/team/tasks', { id: randomUUID(), operationId: randomUUID(), responsibilityScopeId: ids.scope, title: 'Проверить интеграцию задачи', description: 'Синтетическая задача для перехода из чата', assigneeId: ids.drivers[1], dueDate: null }, manager);
    const taskSource = await api('GET', scoped(`/team/messages/${task.messageId}`), undefined, peer);
    assert.equal(taskSource.message.taskId, task.id);
    const mentions = await api('GET', scoped('/team/mentions'), undefined, peer);
    assert.ok(mentions.mentions.some(item => item.messageId === task.messageId));
    const p = await pageFor(peer);
    await p.getByText('Руководитель итогов', { exact: true }).first().click();
    const taskMessage = p.locator(`[data-message-id="${task.messageId}"]`);
    await taskMessage.getByRole('button', { name: '☑ Открыть задачу', exact: true }).click();
    await p.getByRole('dialog').getByText(task.title, { exact: true }).waitFor();
    await p.getByRole('dialog').getByRole('button', { name: /^Закрыть / }).click();
    await a.bringToFront(); await a.reload(); await tabs(a).getByRole('button', { name: 'Итоги', exact: true }).click();
    await a.getByRole('button', { name: 'Руководитель итогов', exact: true }).click();
    await a.getByText('Синтетический приватный черновик недели', { exact: true }).waitFor();
    assert.deepEqual(errors, []);
    console.log('PASS outcomes browser: private durable weekly draft, admin pending compliance, submitted report, crown in chat, required monthly focus, desktop/mobile, task assignment mention and chat-to-task link, no JavaScript errors');
  } finally { if (browser) await browser.close(); await f.close(); }
})().catch(error => { console.error(error.stack || error.message); process.exit(1); });
