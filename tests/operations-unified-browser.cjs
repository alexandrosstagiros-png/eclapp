'use strict';
// Real browser and disposable API/DB: unified lists must retain record ownership.
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { createTestServer } = require('./local-test-server.cjs');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  const fixture = await createTestServer();
  let browser;
  try {
    const { ids, adminPool: db, request } = fixture;
    const extraScope = randomUUID();
    await db.query('INSERT INTO responsibility_scopes(id,project_id,name) VALUES($1,$2,$3)', [extraScope, ids.project, 'Вторая тестовая группа']);
    await db.query('INSERT INTO access_grants(user_id,legal_entity_id,region_id,project_id,responsibility_scope_id,personal_data_visible) VALUES($1,$2,$3,$4,$5,true)', [ids.admin, ids.legal, ids.region, ids.project, extraScope]);
    await db.query('UPDATE access_grants SET personal_data_visible=true WHERE user_id=$1', [ids.admin]);
    const session = await fixture.devLogin(ids.admin);
    const call = async (method, route, body) => {
      const response = await request(method, route, body, session.accessToken);
      assert.ok(response.status >= 200 && response.status < 300, JSON.stringify(response));
      return response.body;
    };
    const access = await call('GET', '/tenders/context');
    const [primaryScope, secondaryScope] = access.scopes.map(scope => scope.responsibilityScopeId);
    assert.equal(access.scopes.length, 2);
    const sharedDriver = randomUUID();
    await db.query('INSERT INTO users(id,display_name,role,active,approved) VALUES($1,$2,$3,true,true)', [sharedDriver, 'Водитель другого каталога', 'driver']);
    await db.query('INSERT INTO access_grants(user_id,legal_entity_id,region_id,project_id,responsibility_scope_id) VALUES($1,$2,$3,$4,$5)', [sharedDriver, ids.legal, ids.region, ids.project, primaryScope]);
    const customers = [], tenders = [], tickets = [];
    for (const [index, responsibilityScopeId] of [primaryScope, secondaryScope].entries()) {
      const customer = await call('PUT', '/tenders/customers', { id: randomUUID(), responsibilityScopeId, version: 0, name: `Общий заказчик ${index + 1}` });
      customers.push(customer);
      tenders.push(await call('PUT', '/tenders/items', { id: randomUUID(), responsibilityScopeId, version: 0, customerId: customer.id, title: `Общий тендер ${index + 1}`, status: 'planned', vehicleCount: '', requirements: '', deliveryType: '', expectedLaunch: null, launchNotes: '', submissionDeadline: null, nextStep: '', nextStepDue: null, kind: 'tender', closeReason: '', winReason: '' }));
      tickets.push(await call('PUT', '/development/tickets', { id: randomUUID(), responsibilityScopeId, version: 0, title: `Общий тикет ${index + 1}`, description: 'Синтетическая проверка общего списка обращений.', section: 'other', status: 'new' }));
      await call('PUT', '/planning', { responsibilityScopeId, businessDate: '2030-06-11', templateId: index ? 'appia' : 'general', templateVersion: 1, rows: [], version: 0 });
    }
    // A new empty technical grant sorts first, but must never absorb new business work.
    const emptyScope = randomUUID();
    await db.query('INSERT INTO responsibility_scopes(id,project_id,name) VALUES($1,$2,$3)', [emptyScope, ids.project, 'AAA пустой технический контекст']);
    await db.query('INSERT INTO access_grants(user_id,legal_entity_id,region_id,project_id,responsibility_scope_id,personal_data_visible) VALUES($1,$2,$3,$4,$5,true)', [ids.admin, ids.legal, ids.region, ids.project, emptyScope]);
    assert.equal((await call('GET', '/tenders/context')).scopes[0].responsibilityScopeId, emptyScope);
    browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    await context.addInitScript(value => sessionStorage.setItem('ecl.session.v2', JSON.stringify({ session: value })), { ...session, rememberedDevice: false });
    const page = await context.newPage();
    page.setDefaultTimeout(20000);
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('dialog', dialog => dialog.accept());
    const mutation = (suffix, method) => page.waitForResponse(response => response.url().endsWith(suffix) && response.request().method() === method);
    const checkMutation = async (pending, scope) => {
      const response = await pending;
      assert.ok(response.ok(), await response.text());
      assert.equal(response.request().postDataJSON().responsibilityScopeId, scope);
      return response.json();
    };

    await page.goto(`${fixture.origin}/?section=tenders&responsibilityScopeId=${secondaryScope}`);
    await page.getByRole('heading', { name: 'Тендеры', exact: true }).waitFor();
    await page.locator('.tenders-card').filter({ hasText: tenders[1].title }).waitFor();
    assert.equal(await page.locator('.tenders-card').count(), 2);
    assert.equal(await page.getByLabel('Проект', { exact: true }).count(), 0);
    const tenderCard = page.locator('.tenders-card').filter({ hasText: tenders[1].title });
    let pending = mutation('/tenders/comments', 'POST');
    await tenderCard.getByLabel(`Новый комментарий: ${tenders[1].title}`).fill('Комментарий ко второй карточке');
    await tenderCard.getByRole('button', { name: 'Добавить комментарий', exact: true }).click();
    await checkMutation(pending, secondaryScope);
    await tenderCard.getByText('Комментарий ко второй карточке', { exact: true }).waitFor();
    pending = mutation('/tenders/items', 'PUT');
    await tenderCard.getByLabel(`Статус: ${tenders[1].title}`).selectOption('in_progress');
    await checkMutation(pending, secondaryScope);
    await page.getByRole('button', { name: '+ Новый тендер', exact: true }).click();
    const tenderDialog = page.getByRole('dialog', { name: 'Новый тендер', exact: true });
    await tenderDialog.getByLabel('Заказчик', { exact: true }).selectOption(customers[1].id);
    await tenderDialog.getByLabel('Название тендера или проекта', { exact: true }).fill('Новый тендер второго заказчика');
    pending = mutation('/tenders/items', 'PUT');
    await tenderDialog.getByRole('button', { name: 'Сохранить', exact: true }).click();
    await checkMutation(pending, secondaryScope);
    await tenderDialog.waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: '+ Новый тендер', exact: true }).click();
    await tenderDialog.getByRole('button', { name: 'Новый заказчик', exact: true }).click();
    await tenderDialog.getByLabel('Название заказчика', { exact: true }).fill('Новый заказчик рабочей базы');
    await tenderDialog.getByLabel('Название тендера или проекта', { exact: true }).fill('Новый тендер рабочей базы');
    const customerPending = mutation('/tenders/customers', 'PUT');
    pending = mutation('/tenders/items', 'PUT');
    await tenderDialog.getByRole('button', { name: 'Сохранить', exact: true }).click();
    await checkMutation(customerPending, secondaryScope);
    await checkMutation(pending, secondaryScope);
    await tenderDialog.waitFor({ state: 'hidden' });
    assert.equal((await call('GET', `/tenders?responsibilityScopeId=${emptyScope}`)).customers.length, 0);
    console.log('PASS unified tender list, original comment/status scope and customer-derived new tender scope');

    await page.goto(`${fixture.origin}/?section=development`);
    await page.getByText(tickets[1].title, { exact: true }).waitFor();
    assert.equal(await page.locator('.development-card').count(), 2);
    assert.equal(await page.getByLabel('Проект', { exact: true }).count(), 0);
    await page.getByText(tickets[1].title, { exact: true }).click();
    const ticketDialog = page.getByRole('dialog');
    await ticketDialog.getByLabel('Название', { exact: true }).fill('Уточнённый общий тикет 2');
    pending = mutation('/development/tickets', 'PUT');
    await ticketDialog.getByRole('button', { name: 'Сохранить', exact: true }).click();
    await checkMutation(pending, secondaryScope);
    await ticketDialog.getByLabel('Комментарий', { exact: true }).fill('Проверка исходного контекста тикета');
    pending = mutation('/development/comments', 'POST');
    await ticketDialog.getByRole('button', { name: 'Добавить комментарий', exact: true }).click();
    await checkMutation(pending, secondaryScope);
    await ticketDialog.getByRole('button', { name: 'Закрыть тикет', exact: true }).click();
    await page.getByRole('button', { name: '+ Новый тикет', exact: true }).click();
    const newTicketDialog = page.getByRole('dialog', { name: 'Новый тикет', exact: true });
    await newTicketDialog.getByLabel('Название', { exact: true }).fill('Новый тикет рабочей базы');
    await newTicketDialog.getByLabel('Описание', { exact: true }).fill('Новый тикет должен продолжать существующую рабочую базу.');
    pending = mutation('/development/tickets', 'PUT');
    await newTicketDialog.getByRole('button', { name: 'Создать тикет', exact: true }).click();
    await checkMutation(pending, primaryScope);
    assert.equal((await call('GET', `/development?responsibilityScopeId=${emptyScope}`)).tickets.length, 0);
    console.log('PASS new customer/tender and ticket prefer populated sources over the first empty technical scope');
    console.log('PASS unified development list and original ticket/comment scope');

    await page.goto(`${fixture.origin}/?section=planning`);
    await page.getByLabel('Дата рейсов', { exact: true }).waitFor();
    await page.getByLabel('Дата рейсов', { exact: true }).fill('2030-06-11');
    await page.locator('.planning-document').nth(1).waitFor();
    assert.equal(await page.locator('.planning-document').count(), 2);
    assert.equal(await page.getByLabel('Проект', { exact: true }).count(), 0);
    const secondaryPlan = page.locator('.planning-document').filter({ hasText: 'APPIA' });
    if (await secondaryPlan.getByRole('button').isDisabled()) await page.locator('.planning-document').filter({ hasText: 'Общая форма' }).getByRole('button').click();
    await secondaryPlan.getByRole('button').click();
    await page.waitForFunction(() => document.querySelector('[aria-label="Форма подачи клиенту"]')?.value === 'appia@1');
    await page.getByLabel('Форма подачи клиенту', { exact: true }).selectOption('metro@1');
    pending = mutation('/planning', 'PUT');
    await page.getByRole('button', { name: 'Сохранить план', exact: true }).click();
    await checkMutation(pending, secondaryScope);
    const original = await call('GET', `/planning?date=2030-06-11&responsibilityScopeId=${primaryScope}`);
    assert.equal(original.templateId, 'general');
    await page.getByText('План сохранён', { exact: true }).waitFor();
    await page.getByLabel('Дата рейсов', { exact: true }).fill('2030-06-12');
    await page.getByRole('button', { name: 'Добавить первое назначение', exact: true }).click();
    const assignment = page.getByRole('dialog', { name: 'Новое назначение', exact: true });
    await assignment.getByLabel('Водитель для назначения', { exact: true }).selectOption(sharedDriver);
    await assignment.getByRole('button', { name: 'Добавить назначение', exact: true }).click();
    await page.locator('.planning-assignment').first().waitFor();
    assert.equal(await page.locator('select[aria-label="Водитель"]').inputValue(), sharedDriver);
    pending = mutation('/planning', 'PUT');
    await page.getByRole('button', { name: 'Сохранить план', exact: true }).click();
    const routedPlan = await checkMutation(pending, primaryScope);
    assert.equal(routedPlan.rows[0].driverId, sharedDriver);
    await page.getByText('План сохранён', { exact: true }).waitFor();
    await page.getByLabel('Дата рейсов', { exact: true }).fill('2030-06-13');
    await page.getByRole('button', { name: 'Календарь', exact: true }).click();
    await page.getByRole('heading', { name: 'Календарь', exact: true }).waitFor();
    assert.equal(await page.getByLabel('Проект', { exact: true }).count(), 0);
    const otherPlans = page.getByRole('region', { name: 'Другие планы за период', exact: true });
    await otherPlans.getByText('Назначений: 1', { exact: true }).waitFor();
    await otherPlans.locator('article').filter({ hasText: 'Назначений: 1' }).getByRole('button', { name: 'Открыть план', exact: true }).click();
    await page.locator('.planning-assignment').first().waitFor();
    assert.equal(await page.getByLabel('Дата рейсов', { exact: true }).inputValue(), '2030-06-12');
    assert.equal(await page.locator('select[aria-label="Водитель"]').inputValue(), sharedDriver);
    assert.deepEqual(errors, []);
    console.log('PASS existing planning documents, driver-based new plan routing and cross-context calendar discovery; no project selectors or browser errors');
  } finally { if (browser) await browser.close(); await fixture.close(); }
})().catch(error => { console.error(error.stack); process.exit(1); });
