'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { createTestServer } = require('./local-test-server.cjs');
(async () => {
  const f = await createTestServer({ builtFrontend: process.env.PLANNING_BUILT_FRONTEND === 'true' });
  let browser;
  try {
    await f.adminPool.query('UPDATE access_grants SET personal_data_visible=true WHERE user_id=ANY($1::uuid[])', [[f.ids.admin, f.ids.dispatcher]]);
    await f.adminPool.query("UPDATE users SET role='manager' WHERE id=$1", [f.ids.dispatcher]);
    const admin = await f.devLogin(f.ids.admin);
    const password = await f.request('POST', `/access/users/${f.ids.dispatcher}/password`, { phone: '+79990000861' }, admin.accessToken);
    assert.equal(password.status, 201);
    browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('dialog', dialog => dialog.accept());
    await page.goto(f.origin);
    await page.locator('#login-phone').fill('+79990000861');
    await page.locator('#login-password').fill(password.body.password);
    await page.getByRole('button', { name: 'Войти', exact: true }).click();
    await page.getByRole('button', { name: 'Добавить первое назначение', exact: true }).click();
    const row = page.locator('.planning-assignment').first();
    const options = await f.request('GET', `/planning/options?responsibilityScopeId=${f.ids.scope}`, undefined, admin.accessToken);
    await row.locator('select[aria-label="Водитель"]').selectOption(f.ids.drivers[0]);
    await row.getByLabel('Машина', { exact: true }).selectOption(options.body.vehicles[0].id);
    await page.getByLabel('Блок для назначений дня', { exact: true }).selectOption('crew');
    await page.getByLabel('Ответственный для назначений дня', { exact: true }).selectOption(f.ids.dispatcher);
    await page.getByLabel('Город для назначений дня', { exact: true }).fill('Санкт-Петербург');
    await page.getByLabel('Клиент для назначений дня', { exact: true }).fill('Хофф');
    await page.getByRole('button', { name: 'Применить к назначениям дня', exact: true }).click();
    assert.equal(await row.getByLabel('Блок отчёта', { exact: true }).inputValue(), 'crew');
    assert.equal(await row.getByLabel('Город выпуска', { exact: true }).inputValue(), 'Санкт-Петербург');
    assert.equal(await row.getByLabel('Клиент выпуска', { exact: true }).inputValue(), 'Хофф');
    await row.getByLabel('Принадлежность машины', { exact: true }).selectOption('own');
    await row.getByLabel('Требуется в экипаже', { exact: true }).fill('2');
    await row.getByLabel('Вышло в экипаже', { exact: true }).fill('2');
    await row.getByLabel('Рейсов на линии (факт)', { exact: true }).fill('2');
    await page.getByRole('button', { name: 'Сохранить план', exact: true }).click();
    await page.getByText('План сохранён', { exact: true }).waitFor();
    await page.reload();
    await row.waitFor();
    assert.equal(await row.getByLabel('Рейсов на линии (факт)', { exact: true }).inputValue(), '2');
    assert.equal(await row.getByLabel('Ответственный за выпуск', { exact: true }).inputValue(), f.ids.dispatcher);
    const directory = path.resolve(__dirname, '../.local/fleet-reports-qa');
    await fs.mkdir(directory, { recursive: true });
    await page.screenshot({ path: path.join(directory, 'planning-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(directory, 'planning-mobile.png'), fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await row.locator('select[aria-label="Водитель"]').selectOption('');
    assert.equal(await row.getByLabel('Рейсов на линии (факт)', { exact: true }).inputValue(), '');
    assert.equal(await row.getByLabel('Вышло в экипаже', { exact: true }).inputValue(), '');
    assert.equal(await row.getByLabel('Принадлежность машины', { exact: true }).inputValue(), 'own');
    await row.getByLabel('Статус', { exact: true }).selectOption('no_driver');
    await row.getByLabel('Рейсов на линии (факт)', { exact: true }).fill('0');
    await page.getByRole('button', { name: 'Сохранить план', exact: true }).click();
    await page.getByText('План сохранён', { exact: true }).waitFor();
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ dailyFacts: 'persisted', bulkAttribution: 'passed', replacementClearsFacts: 'passed', mobileOverflow: false, javascriptErrors: 0 }));
  } finally { if (browser) await browser.close(); await f.close(); }
})().catch(error => { console.error(error); process.exit(1); });
